/// Encodes the Chinese legacy charsets used by reading-source request rules.
///
/// The bundled GBK map supplies the common double-byte repertoire. Compact
/// deltas below align it with Java's GB2312, GBK, and GB18030-2022 encoders;
/// GB18030 four-byte ranges come from the WHATWG Encoding Standard index.
///
/// Data regeneration/verification:
/// 1. Use Android Studio JBR OpenJDK 25.0.3 `Charset.forName` to dump every
///    Unicode scalar encoded by GB2312, GBK, and GB18030.
/// 2. Compare two-byte rows with `json_char_to_gbk`. Encode GB2312's 7445
///    assigned cells as the 87-by-94 bitmap below; retain only differing Java
///    rows in the delta maps and compress consecutive PUA rows into triples.
/// 3. Parse https://encoding.spec.whatwg.org/index-gb18030-ranges.txt
///    (2024-09-18, identifier f963aaa1653f630c523e7b04729fb4e4458f35806c45eb5c179445623138f0c0)
///    into the 207 pointer/code-point pairs below, then retain the 18 Java
///    GB18030-2022 PUA compatibility pointers separately.
/// 4. Compare this encoder byte-for-byte with that JBR dump for all 1,111,936
///    Unicode scalar values and round-trip the GB18030 output through decoder.
List<int> encodeChineseCharset(String text, String charset) {
  final name = charset.trim().toLowerCase().replaceAll(RegExp(r'[-_]'), '');
  if (name != 'gb2312' &&
      name != 'gbk' &&
      name != 'cp936' &&
      name != 'windows936' &&
      name != 'gb18030') {
    throw FormatException('Unsupported Chinese charset: $charset');
  }
  final output = <int>[];
  for (final rune in text.runes) {
    if (rune < 0x80) {
      output.add(rune);
      continue;
    }
    final code = switch (name) {
      'gb2312' => _gb2312Code(rune),
      'gb18030' => _gb18030DoubleByteCode(rune),
      _ => _gbkCode(rune),
    };
    if (code != null) {
      output
        ..add(code >> 8)
        ..add(code & 0xff);
    } else if (name == 'gb18030') {
      output.addAll(_gb18030FourBytes(rune));
    } else {
      output.add(0x3f);
    }
  }
  return output;
}

/// Decodes GB18030-2022 without treating four-byte sequences as GBK pairs.
String decodeGb18030(List<int> bytes) {
  final output = StringBuffer();
  for (var index = 0; index < bytes.length;) {
    final first = bytes[index++] & 0xff;
    if (first < 0x80) {
      output.writeCharCode(first);
      continue;
    }
    if (first < 0x81 || first > 0xfe || index >= bytes.length) {
      output.writeCharCode(0xfffd);
      continue;
    }
    final second = bytes[index] & 0xff;
    if (second >= 0x30 && second <= 0x39) {
      if (index + 2 >= bytes.length) {
        index = bytes.length;
        output.writeCharCode(0xfffd);
        continue;
      }
      final third = bytes[index + 1] & 0xff;
      final fourth = bytes[index + 2] & 0xff;
      if (third < 0x81 || third > 0xfe || fourth < 0x30 || fourth > 0x39) {
        index++;
        output.writeCharCode(0xfffd);
        continue;
      }
      index += 3;
      final pointer =
          (first - 0x81) * 12600 +
          (second - 0x30) * 1260 +
          (third - 0x81) * 10 +
          fourth -
          0x30;
      final rune = _gb18030RangeRune(pointer);
      output.writeCharCode(rune ?? 0xfffd);
      continue;
    }
    if ((second >= 0x40 && second <= 0x7e) ||
        (second >= 0x80 && second <= 0xfe)) {
      index++;
      final code = first << 8 | second;
      final rune =
          _gb18030DeltaByCode[code] ??
          _runeFromRuns(code, _gb18030PrivateUseRuns);
      if (rune != null) {
        output.writeCharCode(rune);
        continue;
      }
      final mapped = json_gbk_to_char[code.toRadixString(16)];
      output.write(mapped ?? '\ufffd');
      continue;
    }
    output.writeCharCode(0xfffd);
  }
  return output.toString();
}

int? _baseCode(int rune) {
  if (rune == 0xfffd) return null;
  final code = json_char_to_gbk[String.fromCharCode(rune)];
  return code != null && code > 0xff ? code : null;
}

int? _gb2312Code(int rune) {
  if (rune == 0x2015) return 0xa1aa;
  if (rune == 0x30fb) return 0xa1a4;
  if (rune == 0x2014 || rune == 0x00b7) return null;
  final code = _baseCode(rune);
  if (code == null) return null;
  final lead = code >> 8;
  final trail = code & 0xff;
  if (lead < 0xa1 || lead > 0xf7 || trail < 0xa1 || trail > 0xfe) {
    return null;
  }
  final index = (lead - 0xa1) * 94 + trail - 0xa1;
  return (_gb2312Assigned[index >> 3] & (1 << (index & 7))) != 0 ? code : null;
}

int? _gbkCode(int rune) {
  if (rune == 0x2295 || rune == 0xfffd) return null;
  return _gbkDelta[rune] ??
      _codeFromRuns(rune, _gbkPrivateUseRuns) ??
      _baseCode(rune);
}

int? _gb18030DoubleByteCode(int rune) {
  if (rune == 0xfffd) return null;
  return _gb18030Delta[rune] ??
      _codeFromRuns(rune, _gb18030PrivateUseRuns) ??
      _baseCode(rune);
}

int? _codeFromRuns(int rune, List<int> runs) {
  for (var index = 0; index < runs.length; index += 3) {
    final start = runs[index];
    final end = runs[index + 1];
    if (rune < start) return null;
    if (rune <= end) {
      return _codeFromPointer(_codePointer(runs[index + 2]) + rune - start);
    }
  }
  return null;
}

int? _runeFromRuns(int code, List<int> runs) {
  final pointer = _codePointer(code);
  for (var index = 0; index < runs.length; index += 3) {
    final startRune = runs[index];
    final endRune = runs[index + 1];
    final startPointer = _codePointer(runs[index + 2]);
    final endPointer = startPointer + endRune - startRune;
    if (pointer < startPointer) continue;
    if (pointer <= endPointer) return startRune + pointer - startPointer;
  }
  return null;
}

int _codePointer(int code) {
  final lead = code >> 8;
  final trail = code & 0xff;
  return (lead - 0x81) * 190 + trail - (trail < 0x7f ? 0x40 : 0x41);
}

int _codeFromPointer(int pointer) {
  final lead = pointer ~/ 190 + 0x81;
  final trailing = pointer % 190;
  return (lead << 8) | trailing + (trailing < 0x3f ? 0x40 : 0x41);
}

List<int> _gb18030FourBytes(int rune) {
  var pointer =
      _gb18030FourByteDelta[rune] ??
      (rune == 0xe7c7 ? 7457 : _gb18030RangePointer(rune));
  final byte1 = pointer ~/ 12600;
  pointer %= 12600;
  final byte2 = pointer ~/ 1260;
  pointer %= 1260;
  return [
    byte1 + 0x81,
    byte2 + 0x30,
    pointer ~/ 10 + 0x81,
    pointer % 10 + 0x30,
  ];
}

int _gb18030RangePointer(int rune) {
  var low = 0;
  var high = _gb18030Ranges.length ~/ 2 - 1;
  while (low < high) {
    final middle = (low + high + 1) ~/ 2;
    if (_gb18030Ranges[middle * 2 + 1] <= rune) {
      low = middle;
    } else {
      high = middle - 1;
    }
  }
  final index = low * 2;
  return _gb18030Ranges[index] + rune - _gb18030Ranges[index + 1];
}

int? _gb18030RangeRune(int pointer) {
  if ((pointer > 39419 && pointer < 189000) || pointer > 1237575) {
    return null;
  }
  final compatibilityRune = _gb18030FourByteDeltaByPointer[pointer];
  if (compatibilityRune != null) return compatibilityRune;
  if (pointer == 7457) return 0xe7c7;
  var low = 0;
  var high = _gb18030Ranges.length ~/ 2 - 1;
  while (low < high) {
    final middle = (low + high + 1) ~/ 2;
    if (_gb18030Ranges[middle * 2] <= pointer) {
      low = middle;
    } else {
      high = middle - 1;
    }
  }
  final index = low * 2;
  return _gb18030Ranges[index + 1] + pointer - _gb18030Ranges[index];
}

